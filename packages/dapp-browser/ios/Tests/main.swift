import Foundation

var failures = 0
func expect(_ value: @autoclosure () -> Bool, _ message: String) {
    if !value() { failures += 1; print("FAIL: \(message)") }
}

let state = BreadPresentationState(timeout: 30)
let first = state.beginNavigation()
state.configure(.fullscreen, generation: first)
expect(state.phase == .preparing, "configuration keeps opaque preparation")
let second = state.beginNavigation()
state.configure(.fullscreen, generation: second)
expect(!state.ready(generation: first), "old document cannot mark ready")
expect(state.ready(generation: second), "current document accepts readiness")
expect(state.phase == .preparing, "document ready alone cannot reveal")
state.layoutPrepared(generation: first)
expect(state.phase == .preparing, "old paint cannot reveal")
state.layoutPrepared(generation: second)
expect(state.phase == .visible, "current ready document and paint reveal")
state.invalidateLayout()
expect(state.phase == .preparing, "rotation closes paint gate")
state.elapse(100)
expect(state.phase == .preparing, "rotation after first reveal cannot expire readiness again")
state.requestVisibility(false)
state.layoutPrepared(generation: second)
expect(state.phase == .temporarilyHidden, "paint cannot restore hidden session")
state.requestVisibility(true)
expect(state.phase == .visible, "resume preserves ready live document")
expect(state.close(), "first close owns teardown")
expect(!state.close(), "repeat close cannot emit another event")
expect(!state.requestVisibility(true), "close is terminal")
expect(!state.ready(generation: second), "closed readiness rejected")
expect(!state.configure(.browser, generation: second), "closed configuration rejected")
expect(state.beginNavigation() == second, "closed generation cannot advance")

let loading = BreadPresentationState(timeout: 30)
let generation = loading.beginNavigation()
loading.configure(.fullscreen, generation: generation)
loading.elapse(29)
expect(loading.phase == .preparing, "deadline is 30 foreground seconds")
loading.setForeground(false)
loading.elapse(100)
expect(loading.remaining == 1, "background does not consume deadline")
loading.setForeground(true)
loading.requestVisibility(false)
loading.elapse(100)
expect(loading.remaining == 1, "parked/approval-hidden time does not consume deadline")
loading.requestVisibility(true)
loading.elapse(1)
expect(loading.phase == .error, "deadline shows recoverable error")
expect(!loading.ready(generation: generation), "late ready cannot bypass error")
let retry = loading.beginNavigation()
expect(loading.remaining == 30, "retry resets foreground allowance")
loading.fail(generation: generation)
expect(loading.phase == .preparing, "old failure cannot fail retry")
loading.fail(generation: retry)
expect(loading.phase == .error, "current load failure produces error")

expect(BreadPresentationState.acceptsMessage(mainFrame: true, messageToken: "new", documentToken: "new", startedGeneration: 2, currentGeneration: 2), "current main document authorized")
expect(!BreadPresentationState.acceptsMessage(mainFrame: false, messageToken: "new", documentToken: "new", startedGeneration: 2, currentGeneration: 2), "iframe rejected")
expect(!BreadPresentationState.acceptsMessage(mainFrame: true, messageToken: "old", documentToken: "new", startedGeneration: 2, currentGeneration: 2), "old token rejected")
expect(!BreadPresentationState.acceptsMessage(mainFrame: true, messageToken: "new", documentToken: "new", startedGeneration: 1, currentGeneration: 2), "navigation during token evaluation rejected")
expect(!BreadPresentationState.acceptsMessage(mainFrame: true, messageToken: "", documentToken: "", startedGeneration: 2, currentGeneration: 2), "empty token rejected")

let hiddenOpening = BreadPresentationState(timeout: 30, initiallyVisible: false)
let hiddenGeneration = hiddenOpening.beginNavigation()
hiddenOpening.configure(.fullscreen, generation: hiddenGeneration)
hiddenOpening.ready(generation: hiddenGeneration)
hiddenOpening.layoutPrepared(generation: hiddenGeneration)
hiddenOpening.elapse(100)
expect(hiddenOpening.phase == .temporarilyHidden, "initial hidden readiness and paint cannot reveal")
expect(hiddenOpening.remaining == 30, "initial hidden startup does not consume readiness deadline")
hiddenOpening.requestVisibility(true)
expect(hiddenOpening.phase == .visible, "explicit visibility restores same prepared document")

print("Bread presentation lifecycle: \(failures) failures")
exit(failures == 0 ? 0 : 1)

import { writeFileSync } from 'node:fs';
import { Address, Endpoint, NoteFile, NoteId, RpcClient } from '@miden-sdk/miden-sdk';
import { expect, test } from '../../fixtures/two-wallets';
import { vaultBalanceByFaucetId } from '../../helpers/balance-truth';
import { readTransactionRows } from '../../helpers/history';
import { restoreMainnetLoopGuardian } from '../../helpers/mainnet-loop-wallet';
import { loadMainnetSwapCheckpoint } from '../../helpers/mainnet-swap-checkpoint';
import { readMainnetSwapPayback, prepareMainnetSwapClaimRecovery } from '../../helpers/mainnet-swap-claim';
import { readMainnetMidenOwnNoteCreator } from '../../helpers/mainnet-miden-read';
import { exportPublicInputNote } from '../../helpers/swap';

test.use({ injectFeeFaucet: false });
test.describe.configure({ mode: 'serial', retries: 0 });
test('read-only already funded first return and exact unclaimed native payout', async ({ walletB }) => {
  test.setTimeout(240000);
  const state=loadMainnetSwapCheckpoint('test-results/original-authority/roundtrip.json');
  if(!state||state.sourceRunId!=='43511695178'||state.authorizationRunId!=='43596925757'||state.phase!=='reverse-authorized'||!state.reverseRequestAuthority||state.reverseClaimAuthority) throw new Error('Wrong retained funded return');
  const authority=state.reverseRequestAuthority;
  expect(authority.nonce).toBe('95a348fa-1212-4661-94bc-99527c24df3b');
  expect(authority.noteId).toBe('0xf41d27eecb4f68ee60bb1e7d84165f8b7e81366caaae2e054ceef6acdf63ccf5');
  const report:Record<string,unknown>={purpose:'read-only funded return readiness; no new return grant, claim policy, signature or execution',inspected:false,retainedReturnNonce:authority.nonce,retainedReturnExpiresAt:authority.expiresAt};
  let stage='restore';
  try {
    await restoreMainnetLoopGuardian(walletB,process.env.E2E_MAINNET_GUARDIAN_KEY_PAIR??'');
    expect(await walletB.getAccountAddress()).toBe(state.account);
    await walletB.refreshBalancesLanded(90000);
    stage='balances';
    const native=await vaultBalanceByFaucetId(walletB.page,state.native.faucetId);
    const requested=await vaultBalanceByFaucetId(walletB.page,state.request.faucetId);
    report.balances={native:native.toString(),requested:requested.toString()};
    stage='public-original';
    const rpc=new RpcClient(new Endpoint('https://rpc.mainnet.miden.io'));
    const firstHeader=await rpc.getBlockHeaderByNumber();
    const originals=await rpc.getNotesById([NoteId.fromHex(authority.noteId)]);
    report.originalNoteCount=originals.length;
    if(originals.length===0) {
      expect(native.toString()).toBe(state.returnBaseline!.native);
      expect(requested.toString()).toBe(state.returnAmount);
      expect(Date.now()).toBeGreaterThan(authority.expiresAt);
      await walletB.page.waitForTimeout(5000);
      const lastHeader=await rpc.getBlockHeaderByNumber();
      expect(lastHeader.blockNum()).toBeGreaterThanOrEqual(firstHeader.blockNum());
      const last=await rpc.getNotesById([NoteId.fromHex(authority.noteId)]);
      expect(last.length).toBe(0);
      await walletB.refreshBalancesLanded(90000);
      expect((await vaultBalanceByFaucetId(walletB.page,state.native.faucetId)).toString()).toBe(state.returnBaseline!.native);
      expect((await vaultBalanceByFaucetId(walletB.page,state.request.faucetId)).toString()).toBe(state.returnAmount);
      const keys=['e2e_mainnet_send_authorization','e2e_mainnet_consume_authorization'];
      const stored=await walletB.page.evaluate(async names=>chrome.storage.local.get(names),[...keys,'e2e_mainnet_consume_authorization_required']);
      report.noLivePolicy=keys.every(key=>stored[key]===undefined);
      const marker=stored.e2e_mainnet_consume_authorization_required;
      report.consumeBlocked=marker&&typeof marker==='object'&&Object.keys(marker).length===1&&marker.status==='blocked';
      expect(report.noLivePolicy).toBe(true);expect(report.consumeBlocked).toBe(true);
      report.absence={firstBlock:firstHeader.blockNum(),lastBlock:lastHeader.blockNum(),verifiedAt:Date.now(),noteCount:0,vaultUnchanged:true};
      report.outcome='expired-issued-return-unobserved-onchain';
      report.inspected=true;
      return;
    }
    expect(requested).toBe(0n);
    expect(native).toBe(18985997n);
    stage='public-payback';
    const accountId=Address.fromBech32(state.account).accountId().toString();
    const proof=await readMainnetSwapPayback('https://rpc.mainnet.miden.io',{kind:'swap',accountId,faucetId:state.request.hex,amount:state.returnAmount!,requestedFaucetId:state.offer.hex,requestedAmount:authority.minimumReceive,noteId:authority.noteId,orderId:authority.orderId});
    report.payback=proof?{...proof,amount:proof.amount.toString()}:null;
    report.unclaimed=proof!==undefined&&proof.claimedAtBlock===undefined;
    if(!proof||proof.claimedAtBlock!==undefined) throw new Error('Exact payout is not unclaimed');
    stage='portfolio-reserve';
    report.preparedLegCreationDebits=prepareMainnetSwapClaimRecovery(state,proof,{offer:native,native,request:requested},'reverse').toString();
    expect(report.preparedLegCreationDebits).toBe('133');
    stage='creator-proof';
    const creator=await readMainnetMidenOwnNoteCreator(authority.noteId,accountId);
    expect(creator.blockNumber).toBe(proof.originalCreatedAtBlock);
    report.creatorBlock=creator.blockNumber;
    stage='export';
    const file=NoteFile.deserialize(Buffer.from(await exportPublicInputNote(walletB,proof.noteId),'hex'));
    expect(file.noteId()?.toString()).toBe(proof.noteId);expect(file.inclusionProof()).toBeDefined();
    report.inputFileReady=true;
    stage='pending-control';
    await walletB.triggerSync(true);
    await walletB.navigateTo('/history?filter=pending&view=list');
    const accept=walletB.page.locator(`[data-pending-note-id="${proof.noteId}"]`).getByRole('button',{name:/^Accept Transfer$/});
    await expect(accept).toBeVisible({timeout:60000});
    await expect(accept).toBeEnabled({timeout:60000});
    report.acceptVisible=true;report.acceptEnabled=true;
    stage='history';
    const rows=await readTransactionRows(walletB.page);
    report.unresolvedRows=rows.some(row=>row.status===0||row.status===1||row.status===4);
    const keys=['e2e_mainnet_send_authorization','e2e_mainnet_consume_authorization'];
    const stored=await walletB.page.evaluate(async names=>chrome.storage.local.get(names),[...keys,'e2e_mainnet_consume_authorization_required']);
    report.noLivePolicy=keys.every(key=>stored[key]===undefined);
    const marker=stored.e2e_mainnet_consume_authorization_required;
    report.consumeBlocked=marker&&typeof marker==='object'&&Object.keys(marker).length===1&&marker.status==='blocked';
    expect(report.noLivePolicy).toBe(true);expect(report.consumeBlocked).toBe(true);expect(report.unresolvedRows).toBe(false);
    report.inspected=true;
  } catch(error) {
    report.errorStage=stage;
    const message=error instanceof Error?error.message:'';
    const known=[['missing-original','Missing exact original public PSWAP'],['original-identity','Original recorded protocol identity is not committed'],['ambiguous-maker','Ambiguous or oversized maker-block'],['payback-mismatch','Payback differs from the exact original'],['original-order','Original protocol order changed'],['portfolio','Current creation debit'],['claim-ledger','fee ledger'],['timeout','Timeout']].find(([,text])=>message.includes(text));
    report.errorCode=known?.[0]??'unclassified';
  } finally {writeFileSync('test-results/read-only-funded-return.json',JSON.stringify(report,null,2));}
  expect(report.inspected).toBe(true);
  expect(report.unclaimed).toBe(true);
});
